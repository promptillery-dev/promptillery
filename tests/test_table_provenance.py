def test_all_files_exist():
    """Test that all file paths in rows exist relative to REPO_ROOT."""
    rows = tp.build_rows(REPO_ROOT)
    missing_files = []
    for row in rows:
        # Skip "pending" value rows (they reference files that don't exist yet)
        if row.get("value") == "pending":
            continue
        file_path = REPO_ROOT / row["file"]
        if not file_path.exists():
            missing_files.append((row, file_path))

    assert not missing_files, (
        f"Missing files: {[(r['file'], p) for r, p in missing_files]}"
    )


def test_render_output():
    """Test that render() produces valid markdown table with correct structure."""
    rows = tp.build_rows(REPO_ROOT)
    output = tp.render(rows)
    lines = output.split("\n")

    # Assert first line is the header
    assert lines[0] == "# Table provenance (generated by scripts/table_provenance.py)", (
        f"First line should be header, got: {lines[0]}"
    )

    # Assert line 3 (index 2) is the column header
    assert lines[2] == "| table | row | column | value | file |", (
        f"Line 3 should be column header, got: {lines[2]}"
    )

    # Assert line 4 (index 3) is the separator with exactly 5 cells
    assert lines[3] == "|---|---|---|---|---|", (
        f"Line 4 should be separator, got: {lines[3]}"
    )

    # Assert every data line has exactly 5 cells
    data_lines = [line for line in lines[4:] if line.strip()]  # Skip empty lines
    assert len(data_lines) == len(rows), (
        f"Expected {len(rows)} data lines, got {len(data_lines)}"
    )

    for i, line in enumerate(data_lines):
        cells = [c.strip() for c in line.split("|")[1:-1]]  # Remove outer pipes
        assert len(cells) == 5, (
            f"Line {i} should have 5 cells, got {len(cells)}: {line}"
        )


def test_main_with_output_option():
    """Test that main() respects --output option."""
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        output_file = tmp_path / "custom.md"

        # Call main with custom output path
        result = tp.main(["--output", str(output_file)])

        assert result == 0, "main() should return 0"
        assert output_file.exists(), f"Output file should exist at {output_file}"

        # Verify default output file is untouched
        default_file = REPO_ROOT / "docs" / "TABLE_PROVENANCE.md"
        original_mtime = default_file.stat().st_mtime

        # Call main again with custom output (should not touch default)
        tp.main(["--output", str(tmp_path / "another.md")])
        assert default_file.stat().st_mtime == original_mtime, (
            "Default output file should not be modified"
        )

        # Verify custom output has correct structure
        content = output_file.read_text()
        assert content.startswith("# Table provenance"), "Output should have correct header"
        lines = content.split("\n")
        assert lines[2] == "| table | row | column | value | file |", (
            "Output should have correct column header"
        )


