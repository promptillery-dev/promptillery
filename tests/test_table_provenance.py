def test_table2_loop_rows_latest_ablation_dir_wins(tmp_path):
    """Two ablation directories for one dataset: only the later timestamp is indexed."""
    import json as _json
    g3 = tmp_path / "out" / "g3"
    for stamp, acc in (("20260101_000000", 0.10), ("20260922_120000", 0.90)):
        arm = g3 / f"ablation_g3_sst2_roberta_base_transformers_{stamp}" / f"g3_sst2_roberta_base_transformers_cycles-5_{stamp}_000000_s13_ab_cd"
        arm.mkdir(parents=True)
        (arm / "metrics.json").write_text(_json.dumps({"heldout_test": {"accuracy": acc}}))
    rows = tp._table2_loop_rows(tmp_path)
    assert [r["value"] for r in rows] == ["90.00"]
    assert "20260922_120000" in rows[0]["file"]


def test_table2_loop_rows_bs_rerun_dir_wins_and_tags_value(tmp_path):
    """An out-of-memory re-run at batch 16 is a later ``_bs16`` directory: it is indexed, tagged, and the
    failed batch-32 arms (no held-out accuracy) are skipped."""
    import json as _json
    g3 = tmp_path / "out" / "g3"
    failed = g3 / "ablation_g3_imdb_ettin_encoder_w10_20260922_191235" / "g3_imdb_ettin_encoder_w10_cycles-10_20260922_191254_000000_s13_ab_cd"
    failed.mkdir(parents=True)
    (failed / "metrics.json").write_text(_json.dumps({"status": "failed"}))
    rerun = g3 / "ablation_g3_imdb_ettin_encoder_w10_bs16_20260922_191655" / "g3_imdb_ettin_encoder_w10_bs16_cycles-10_20260922_201756_000000_s13_ab_cd"
    rerun.mkdir(parents=True)
    (rerun / "metrics.json").write_text(_json.dumps({"heldout_test": {"accuracy": 0.93328}}))
    rows = tp._table2_loop_rows(tmp_path)
    assert [(r["row"], r["column"], r["value"]) for r in rows] == [
        ("ettin_encoder promptillery (10 cycles)", "imdb", "93.33 (bs16)")
    ]
    assert "_bs16_" in rows[0]["file"]

